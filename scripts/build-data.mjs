// Builds src/data.js from data/guess-k*.json (scripts/guess-table.mjs runs) and the exact TV distances.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tvDistance } from '../src/cards.js';
const BD = [31.17, 19.69, 12.92, 8.80, 6.56, 5.51, 5.01, 4.76, 4.65, 4.60]; // Bayer & Diaconis 1992, Table 5 (McGrath's strategy)
const rows = {};
for (let k = 1; k <= 10; k++) {
  const f = new URL(`../data/guess-k${k}.json`, import.meta.url);
  if (!existsSync(f) || !readFileSync(f, 'utf8').trim()) throw new Error(`missing data for k=${k}`);
  const d = JSON.parse(readFileSync(f, 'utf8'));
  rows[k] = { mean: +d.mean.toFixed(3), se: +d.se.toFixed(3), decks: d.T, tv: +tvDistance(52, k).toFixed(4), bd: BD[k - 1] };
}
writeFileSync(new URL('../src/data.js', import.meta.url),
  `// Generated by scripts/build-data.mjs. mean/se: the essay's guesser (most likely next card, exact odds), 52 cards, k riffles,\n` +
  `// averaged over 'decks' random decks. tv: exact total variation distance. bd: Bayer & Diaconis 1992 Table 5.\n` +
  `export const CHANCE = ${(() => { let s = 0; for (let i = 1; i <= 52; i++) s += 1 / i; return s.toFixed(3); })()};\n` +
  `export const GUESS_TABLE = ${JSON.stringify(rows, null, 0).replace(/},/g, '},\n  ')};\n`);
console.log('wrote src/data.js');
